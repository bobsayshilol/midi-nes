#include "midines.h"
#include <cstdio>
#include <cstdlib>
#include <chrono>
#include <thread>

//
// All these examples are taken from https://www.nesdev.org/wiki/APU_basics
//

namespace {

void init_apu(MIDINES_State* state) {
    const uint8_t regs[20] = {
        0x30, 0x08, 0x00, 0x00,
        0x30, 0x08, 0x00, 0x00,
        0x80, 0x00, 0x00, 0x00,
        0x30, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00,
    };
    for (int y = 0x13; y >= 0; y--) {
        midines_write(state, 0x4000 + y, regs[y]);
    }
    midines_write(state, 0x4015, 0x0f);
    midines_write(state, 0x4017, 0x40);
}

void loop_for_frames(MIDINES_State* state, int frames) {
    while (frames --> 0) {
        midines_update(state);
        std::this_thread::sleep_for(std::chrono::milliseconds(1000 / 60));
    }
}

void play_pulse(MIDINES_State* state) {
    printf("%s\n", __func__);

    init_apu(state);
    midines_write(state, 0x4002, (279 >> 0) & 0xff);    // #<279
    midines_write(state, 0x4003, (279 >> 8) & 0xff);    // #>279
    midines_write(state, 0x4000, 0b10111111);

    loop_for_frames(state, 60);
}

void play_triangle(MIDINES_State* state) {
    printf("%s\n", __func__);

    init_apu(state);
    midines_write(state, 0x400A, (139 >> 0) & 0xff);    // #<139
    midines_write(state, 0x400B, (139 >> 8) & 0xff);    // #>139
    midines_write(state, 0x4008, 0b11000000);
    midines_write(state, 0x4017, 0b11000000);

    loop_for_frames(state, 60);
}

void play_noise(MIDINES_State* state) {
    printf("%s\n", __func__);

    init_apu(state);
    midines_write(state, 0x400E, 0b10000101);
    midines_write(state, 0x400C, 0b00111111);

    loop_for_frames(state, 60);
}

void play_notes(MIDINES_State* state, bool change_instruments) {
    printf("%s\n", __func__);

    const uint8_t periodTableLo[] = {
        0xf1, 0x7f, 0x13, 0xad, 0x4d, 0xf3, 0x9d, 0x4c, 0x00, 0xb8, 0x74, 0x34,
        0xf8, 0xbf, 0x89, 0x56, 0x26, 0xf9, 0xce, 0xa6, 0x80, 0x5c, 0x3a, 0x1a,
        0xfb, 0xdf, 0xc4, 0xab, 0x93, 0x7c, 0x67, 0x52, 0x3f, 0x2d, 0x1c, 0x0c,
        0xfd, 0xef, 0xe1, 0xd5, 0xc9, 0xbd, 0xb3, 0xa9, 0x9f, 0x96, 0x8e, 0x86,
        0x7e, 0x77, 0x70, 0x6a, 0x64, 0x5e, 0x59, 0x54, 0x4f, 0x4b, 0x46, 0x42,
        0x3f, 0x3b, 0x38, 0x34, 0x31, 0x2f, 0x2c, 0x29, 0x27, 0x25, 0x23, 0x21,
        0x1f, 0x1d, 0x1b, 0x1a, 0x18, 0x17, 0x15, 0x14,
    };
    const uint8_t periodTableHi[] = {
        0x07, 0x07, 0x07, 0x06, 0x06, 0x05, 0x05, 0x05, 0x05, 0x04, 0x04, 0x04,
        0x03, 0x03, 0x03, 0x03, 0x03, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02, 0x02,
        0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    };
    static_assert(sizeof(periodTableLo) == sizeof(periodTableHi));

    init_apu(state);
    midines_write(state, 0x4000, 0b10110111);
    for (size_t i = 0; i < sizeof(periodTableLo) / sizeof(periodTableLo[0]); i++) {
        if (change_instruments) {
            midines_set_instruments(state, i, i, 0, 0);
        }
        midines_write(state, 0x4002, periodTableLo[i]);
        midines_write(state, 0x4003, periodTableHi[i]);
        loop_for_frames(state, 5);
    }
}

} // namespace

int main() {
    MIDINES_State* state = midines_open();
    if (!state) {
        printf("Failed to open MIDINES\n");
        return EXIT_FAILURE;
    }

    // Run the examples.
    play_pulse(state);
    play_triangle(state);
    play_noise(state);
    play_notes(state, false);
    play_notes(state, true);

    // Close up shop.
    midines_close(state);
    return EXIT_SUCCESS;
}
